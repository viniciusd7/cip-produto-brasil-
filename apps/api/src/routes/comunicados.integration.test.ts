import assert from "node:assert/strict";
import test from "node:test";
import express from "express";
import { prisma } from "@cip/db";
import { permissionsForRole, signAccessToken } from "../middleware/auth";
import { errorHandler } from "../middleware/error";
import { comunicadosRouter } from "./comunicados";
import { notificacoesRouter } from "./execucao";

const testUrl = process.env.COMUNICACAO_TEST_DATABASE_URL;

test("integração PostgreSQL: conversa, concorrência, leitura, destinatários e revogação", { skip: !testUrl && "Exige PostgreSQL descartável em COMUNICACAO_TEST_DATABASE_URL" }, async (t) => {
  const url = new URL(testUrl!);
  assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(url.hostname));
  assert.equal(url.pathname, "/cip_demo_test_comunicacao");
  process.env.DATABASE_URL = testUrl;
  process.env.DIRECT_URL = testUrl;
  assert.equal(await prisma.user.count(), 0, "O banco de teste precisa estar vazio");
  t.after(() => prisma.$disconnect());
  const cidade = await prisma.municipio.create({ data: { nome: "Cidade QA", ibgeCode: "qa-comunicacao-1", uf: "MG" } });
  const outra = await prisma.municipio.create({ data: { nome: "Outra QA", ibgeCode: "qa-comunicacao-2", uf: "MG" } });
  const saude = await prisma.secretaria.create({ data: { municipioId: cidade.id, nome: "Saúde" } });
  const obras = await prisma.secretaria.create({ data: { municipioId: cidade.id, nome: "Obras" } });
  const cultura = await prisma.secretaria.create({ data: { municipioId: cidade.id, nome: "Cultura" } });
  const projeto = await prisma.iniciativa.create({ data: { municipioId: cidade.id, secretariaPrincipalId: saude.id, codigo: "QA-01", nome: "UBS de teste", secretarias: { create: { secretariaId: obras.id } } } });
  const criarUser = (id: string, role: string, municipioId = cidade.id, secretariaId?: string) => prisma.user.create({ data: { id, email: `${id}@example.invalid`, name: id, passwordHash: "test-only-not-a-password", vinculos: { create: { municipioId, roleCode: role, secretariaId } } } });
  const secretario = await criarUser("qa-secretario", "gestor", cidade.id, saude.id);
  const consultor = await criarUser("qa-consultor", "analista");
  const prefeito = await criarUser("qa-prefeito", "prefeito");
  const correlato = await criarUser("qa-obras", "gestor", cidade.id, obras.id);
  const externo = await criarUser("qa-externo", "analista", outra.id);
  const tarefa = await prisma.marcoEntrega.create({ data: { iniciativaId: projeto.id, descricao: "Licenciamento de teste" } });
  await prisma.notificacao.create({ data: { municipioId: cidade.id, userId: secretario.id, tipo: "ATRIBUICAO", titulo: "Licenciamento", texto: "Notificação de teste", entidadeTipo: "MARCO", entidadeId: tarefa.id } });
  const app = express(); app.use(express.json()); app.use("/comunicados", comunicadosRouter); app.use("/notificacoes", notificacoesRouter); app.use(errorHandler);
  const server = app.listen(0, "127.0.0.1");
  t.after(() => new Promise<void>((resolve, reject) => { server.close((err) => err ? reject(err) : resolve()); server.closeIdleConnections(); }));
  await new Promise<void>((resolve, reject) => { server.once("listening", resolve); server.once("error", reject); });
  const address = server.address(); assert.ok(address && typeof address !== "string");
  const request = (user: typeof secretario, role: "gestor" | "analista" | "prefeito", path: string, body?: object) => fetch(`http://127.0.0.1:${address.port}${path}`, { method: body ? "POST" : "GET", headers: { Authorization: `Bearer ${signAccessToken({ ...user, role, municipioId: cidade.id, municipioNome: cidade.nome, isPlatformAdmin: false, permissions: permissionsForRole(role) })}`, "Content-Type": "application/json" }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const envio = { iniciativaId: projeto.id, destinatarioId: secretario.id, texto: "Mensagem transacional de teste", envioId: "123e4567-e89b-42d3-a456-426614174111" };
  const responses = await Promise.all(Array.from({ length: 5 }, () => request(consultor, "analista", "/comunicados", envio)));
  assert.equal(responses.filter((r) => r.status === 201).length, 1);
  assert.ok(responses.every((r) => r.status === 200 || r.status === 201), JSON.stringify(await Promise.all(responses.map((r) => r.json()))));
  assert.equal(await prisma.comunicado.count(), 1);
  assert.equal(await prisma.auditLog.count({ where: { action: "SEND_MESSAGE" } }), 1);
  const mensagem = await prisma.comunicado.findFirstOrThrow();
  const central = await request(secretario, "gestor", "/comunicados/avisos");
  assert.equal(central.status, 200);
  assert.equal((await central.json()).naoLidas, 2);
  const destinos = await request(secretario, "gestor", `/comunicados/destinatarios?iniciativaId=${projeto.id}`);
  assert.equal(destinos.status, 200);
  assert.deepEqual((await destinos.json()).data.map((u: { id: string }) => u.id).sort(), [consultor.id, prefeito.id, correlato.id].sort());
  assert.equal((await request(secretario, "gestor", "/comunicados", { ...envio, envioId: undefined, destinatarioId: consultor.id, texto: "Resposta da secretaria" })).status, 201);
  assert.equal((await request(prefeito, "prefeito", "/comunicados", envio)).status, 403);
  assert.equal((await request(consultor, "analista", "/comunicados", { ...envio, destinatarioId: externo.id })).status, 422);
  const leituras = await Promise.all(Array.from({ length: 3 }, () => request(secretario, "gestor", `/comunicados/${mensagem.id}/lido`, {})));
  assert.ok(leituras.every((response) => response.status === 200));
  assert.equal(await prisma.comunicadoLeitura.count(), 1);
  assert.equal((await prisma.marcoEntrega.findUniqueOrThrow({ where: { id: tarefa.id } })).concluidoEm, null);
  await prisma.vinculoUsuarioMunicipio.update({ where: { userId_municipioId: { userId: secretario.id, municipioId: cidade.id } }, data: { secretariaId: cultura.id } });
  assert.deepEqual((await (await request(secretario, "gestor", "/comunicados/avisos")).json()).data, []);
  assert.deepEqual((await (await request(secretario, "gestor", "/notificacoes")).json()).data, []);
  assert.equal((await request(secretario, "gestor", `/comunicados?iniciativaId=${projeto.id}`)).status, 403);
});
